const availableIds = new Set(liveCodingTasks.map((task) => task.id))

export const liveCodingCatalog: CatalogTask[] = [
  ...liveCodingTasks.map((task) => ({
    id: task.id,
    slug: task.slug,
    title: task.title,
    summary: task.summary,
    difficulty: task.difficulty,
    tags: task.tags,
    language: task.solution.language,
    available: true,
    hasTypeScriptSolution: Boolean(task.typescriptSolution),
  })),
  ...plannedTasks
    .filter((task) => !availableIds.has(task.id))
    .map(
      (task): CatalogTask => ({
        ...task,
        language: task.id <= 40 ? 'javascript' : 'tsx',
        available: false,
        hasTypeScriptSolution: false,
      }),
    ),
].sort((a, b) => a.id - b.id)
